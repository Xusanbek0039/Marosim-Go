"""Reviewed API access contract: ``backend/contracts/api_access_contract.json``.

The file is a committed snapshot of every operation's role metadata plus a fingerprint of its
request/response schema. CI compares it with the live schema (``tests/test_api_access_contract.py``),
so a new endpoint, a role/permission change or a schema change cannot land silently — the
developer regenerates it with ``python manage.py api_contract --write`` and the diff is reviewed
(and becomes the API changelog entry).

The snapshot is *documentation of intent*; the runtime matrix in the same test file proves the
permission classes actually behave that way.
"""

import hashlib
import json
from pathlib import Path

from django.conf import settings

from . import catalog

CONTRACT_PATH = Path(settings.BASE_DIR) / "contracts" / "api_access_contract.json"
CONTRACT_FIELDS = (
    "operation_id",
    "allowed_roles",
    "auth_type",
    "required_permissions",
    "role_requirements",
    "ownership_scope",
    "conditions",
    "access_status",
    "deprecated",
    "schema_fingerprint",
)

MATCHES = "MATCHES_CONTRACT"
NOT_IN_CONTRACT = "NOT_IN_CONTRACT"
MISMATCH = "CONTRACT_MISMATCH"
REVIEW_REQUIRED = "REVIEW_REQUIRED"


def _deref(node, components: dict, seen: frozenset = frozenset()):
    if isinstance(node, dict):
        ref = node.get("$ref")
        if ref:
            name = ref.rsplit("/", 1)[-1]
            if name in seen:
                return {"$ref": name}
            return _deref(components.get(name, {}), components, seen | {name})
        return {k: _deref(v, components, seen) for k, v in node.items() if k not in ("description", "example")}
    if isinstance(node, list):
        return [_deref(v, components, seen) for v in node]
    return node


def fingerprint(op: dict, components: dict) -> str:
    """Stable hash of what a client depends on: parameters, request body and response shapes."""
    shape = {
        "parameters": sorted(
            (
                {
                    "name": p.get("name"),
                    "in": p.get("in"),
                    "required": bool(p.get("required")),
                    "schema": _deref(p.get("schema"), components),
                }
                for p in op.get("parameters", [])
            ),
            key=lambda p: (p["in"], p["name"]),
        ),
        "request": _deref((op.get("requestBody") or {}).get("content"), components),
        "responses": {code: _deref(r.get("content"), components) for code, r in op.get("responses", {}).items()},
    }
    raw = json.dumps(shape, sort_keys=True, ensure_ascii=False, default=str)
    return hashlib.sha256(raw.encode()).hexdigest()[:16]


def key(method: str, path: str) -> str:
    return f"{method.upper()} {path}"


def current(schema: dict | None = None) -> dict[str, dict]:
    schema = schema or catalog.get_schema()
    components = schema.get("components", {}).get("schemas", {})
    entries = {}
    for endpoint in catalog.build(schema):
        op = schema["paths"][endpoint["path"]][endpoint["method"].lower()]
        entry = {name: endpoint.get(name) for name in CONTRACT_FIELDS if name in endpoint}
        entry["operation_id"] = endpoint["id"]
        entry["schema_fingerprint"] = fingerprint(op, components)
        entries[key(endpoint["method"], endpoint["path"])] = entry
    return dict(sorted(entries.items()))


def load(path: Path = CONTRACT_PATH) -> dict[str, dict]:
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))["operations"]


def dump(entries: dict[str, dict], path: Path = CONTRACT_PATH) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    doc = {
        "_comment": "Generated by `python manage.py api_contract --write`. Review the diff; do not edit by hand.",
        "operations": entries,
    }
    path.write_text(json.dumps(doc, indent=2, ensure_ascii=False, sort_keys=False) + "\n", encoding="utf-8")


def diff(reviewed: dict[str, dict], live: dict[str, dict]) -> dict:
    changed = {}
    for name in reviewed.keys() & live.keys():
        fields = [f for f in CONTRACT_FIELDS if reviewed[name].get(f) != live[name].get(f)]
        if fields:
            changed[name] = {f: {"from": reviewed[name].get(f), "to": live[name].get(f)} for f in fields}
    return {
        "added": sorted(live.keys() - reviewed.keys()),
        "removed": sorted(reviewed.keys() - live.keys()),
        "changed": dict(sorted(changed.items())),
    }


def status_of(entry: dict, reviewed: dict[str, dict], name: str) -> str:
    if entry.get("access_status") != "DERIVED":
        return REVIEW_REQUIRED
    if name not in reviewed:
        return NOT_IN_CONTRACT
    return MATCHES if reviewed[name] == entry else MISMATCH


def annotate(endpoints: list[dict], schema: dict | None = None) -> list[dict]:
    """Add ``contract_status`` to catalog entries (does not imply the endpoint is healthy)."""
    reviewed, live = load(), current(schema)
    for endpoint in endpoints:
        name = key(endpoint["method"], endpoint["path"])
        endpoint["contract_status"] = status_of(live[name], reviewed, name) if name in live else NOT_IN_CONTRACT
    return endpoints
